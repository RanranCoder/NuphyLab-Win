// Digests and Ed25519 verification for the updater (Sparkle-style EdDSA over
// the installer bytes). The verifying key is compiled into the shell; the
// matching signing seed never leaves the release machine (scripts/
// prepare-appcast-win.mjs --generate-key).

use ed25519_dalek::{Signature, Verifier, VerifyingKey};

/// Base64 (standard alphabet, padding required) → bytes. Whitespace is
/// tolerated because release tooling may wrap the key.
pub fn decode_base64(text: &str) -> Result<Vec<u8>, String> {
    fn value_of(character: u8) -> Result<Option<u8>, String> {
        Ok(match character {
            b'A'..=b'Z' => Some(character - b'A'),
            b'a'..=b'z' => Some(character - b'a' + 26),
            b'0'..=b'9' => Some(character - b'0' + 52),
            b'+' => Some(62),
            b'/' => Some(63),
            b'=' => Some(0),
            b' ' | b'\r' | b'\n' | b'\t' => None,
            other => return Err(format!("invalid base64 character {}", other as char)),
        })
    }
    let bytes: Vec<u8> = text.bytes().filter(|b| value_of(*b).map_or(false, |v| v.is_some())).collect();
    if bytes.is_empty() {
        return Err("empty base64 input".to_string());
    }
    if bytes.len() % 4 != 0 {
        return Err("base64 length must be a multiple of 4".to_string());
    }
    let padding = text.chars().rev().take_while(|c| *c == '=').count();
    let mut out = Vec::with_capacity(bytes.len() / 4 * 3);
    for chunk in bytes.chunks(4) {
        let mut quad = [0u8; 4];
        for (slot, byte) in quad.iter_mut().zip(chunk) {
            *slot = value_of(*byte)?.unwrap_or(0);
        }
        let triple = (quad[0] as u32) << 18 | (quad[1] as u32) << 12 | (quad[2] as u32) << 6 | quad[3] as u32;
        out.push((triple >> 16) as u8);
        out.push((triple >> 8) as u8);
        out.push(triple as u8);
    }
    let trimmed = out.len().saturating_sub(padding.min(2));
    out.truncate(trimmed);
    Ok(out)
}

pub fn sha256_hex(data: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let mut hasher = Sha256::new();
    hasher.update(data);
    let digest = hasher.finalize();
    let mut text = String::with_capacity(digest.len() * 2);
    for byte in digest {
        text.push_str(&format!("{byte:02x}"));
    }
    text
}

/// Verifies the Ed25519 signature over `data`. `public_key_base64` is the
/// 32-byte verifying key (compiled-in release key or the QA override).
pub fn verify_signature(public_key_base64: &str, signature_base64: &str, data: &[u8]) -> Result<(), String> {
    let key_bytes = decode_base64(public_key_base64).map_err(|error| format!("update public key invalid: {error}"))?;
    if key_bytes.len() != 32 {
        return Err(format!("update public key must be 32 bytes, got {}", key_bytes.len()));
    }
    let mut owned = [0u8; 32];
    owned.copy_from_slice(&key_bytes);
    let verifying_key = VerifyingKey::from_bytes(&owned).map_err(|error| format!("update public key rejected: {error}"))?;
    let signature_bytes = decode_base64(signature_base64).map_err(|error| format!("update signature invalid: {error}"))?;
    if signature_bytes.len() != 64 {
        return Err(format!("update signature must be 64 bytes, got {}", signature_bytes.len()));
    }
    let signature = Signature::from_slice(&signature_bytes).map_err(|error| format!("update signature rejected: {error}"))?;
    verifying_key
        .verify(data, &signature)
        .map_err(|_| "update signature does not match the installer".to_string())
}

/// The verifying key baked into release builds. Generated by
/// `node scripts/prepare-appcast-win.mjs --generate-key` and pasted here.
/// AIR_STUDIO_UPDATE_PUBLIC_KEY overrides it for QA runs only.
pub const UPDATE_PUBLIC_KEY: &str = "";

pub fn public_key_for_verification() -> String {
    std::env::var("AIR_STUDIO_UPDATE_PUBLIC_KEY").unwrap_or_else(|_| UPDATE_PUBLIC_KEY.to_string())
}
